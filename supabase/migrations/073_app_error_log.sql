-- Migration 073: Application error log with SysAdmin review
--
-- Every error the app hits (render crashes, failed Supabase calls, unhandled
-- promise rejections) is recorded here so it can be reviewed and closed out.
--
-- 1. app_error_groups       one row per distinct error (by fingerprint), with
--                           its review status: new, acknowledged,
--                           action_required, resolved, ignored.
-- 2. app_error_occurrences  every time it happened: who, which tenant, which
--                           page, when. Capped at the latest 100 per group.
-- 3. log_app_error()        the only way to write. Callable by signed-in users
--                           AND anon (errors on the login page matter too),
--                           so every input is length-capped.
-- 4. review_app_error()     SysAdmin status change with a note.
--
-- A resolved or ignored error that happens again is reopened as `new`
-- (a regression), with `regressed_at` stamped.
--
-- Global, not tenant-scoped: errors are a platform concern reviewed by
-- SysAdmins. Each row still records the tenant it happened in.
--
-- Safe to run more than once.

-- ============================================================================
-- 1. Tables
-- ============================================================================
CREATE TABLE IF NOT EXISTS app_error_groups (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  display_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
  -- Stable hash of source + error name + normalised message + top stack frame
  fingerprint       TEXT NOT NULL UNIQUE,
  source            TEXT NOT NULL DEFAULT 'client',
  error_name        TEXT,
  message           TEXT NOT NULL,
  -- Postgres / PostgREST error code when there is one (e.g. 42501 = RLS)
  code              TEXT,
  stack             TEXT,
  occurrence_count  INTEGER NOT NULL DEFAULT 0,
  affected_users    UUID[] NOT NULL DEFAULT '{}',
  first_seen_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_url          TEXT,
  last_tenant_id    UUID REFERENCES tenants(id) ON DELETE SET NULL,
  release           TEXT,
  status            TEXT NOT NULL DEFAULT 'new',
  resolution_note   TEXT,
  reviewed_by       UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at       TIMESTAMPTZ,
  regressed_at      TIMESTAMPTZ,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT app_error_groups_status_check
    CHECK (status IN ('new', 'acknowledged', 'action_required', 'resolved', 'ignored')),
  CONSTRAINT app_error_groups_source_check
    CHECK (source IN ('client', 'api', 'edge_function', 'database'))
);

CREATE INDEX IF NOT EXISTS idx_app_error_groups_status_seen
  ON app_error_groups (status, last_seen_at DESC);

CREATE TABLE IF NOT EXISTS app_error_occurrences (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  group_id     UUID NOT NULL REFERENCES app_error_groups(id) ON DELETE CASCADE,
  tenant_id    UUID REFERENCES tenants(id) ON DELETE SET NULL,
  user_id      UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  url          TEXT,
  user_agent   TEXT,
  release      TEXT,
  -- Extra detail: Supabase error details/hint, React component stack, the
  -- mutation or query that failed.
  context      JSONB NOT NULL DEFAULT '{}',
  occurred_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_app_error_occurrences_group
  ON app_error_occurrences (group_id, occurred_at DESC);

COMMENT ON TABLE app_error_groups IS
  'Distinct application errors and their SysAdmin review status (migration 073).';
COMMENT ON TABLE app_error_occurrences IS
  'Individual occurrences of an app_error_groups row, latest 100 per group (migration 073).';

-- ============================================================================
-- 2. RLS: SysAdmins read and review; nobody writes directly
-- ============================================================================
ALTER TABLE app_error_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_error_occurrences ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "app_error_groups_select" ON app_error_groups;
CREATE POLICY "app_error_groups_select" ON app_error_groups
  FOR SELECT TO authenticated
  USING (public.is_sys_admin());

DROP POLICY IF EXISTS "app_error_occurrences_select" ON app_error_occurrences;
CREATE POLICY "app_error_occurrences_select" ON app_error_occurrences
  FOR SELECT TO authenticated
  USING (public.is_sys_admin());

-- Writes go through the SECURITY DEFINER functions below only.
REVOKE ALL ON app_error_groups FROM anon, authenticated;
REVOKE ALL ON app_error_occurrences FROM anon, authenticated;
GRANT SELECT ON app_error_groups TO authenticated;
GRANT SELECT ON app_error_occurrences TO authenticated;

-- ============================================================================
-- 3. log_app_error(): record one occurrence
-- ============================================================================
CREATE OR REPLACE FUNCTION public.log_app_error(
  p_fingerprint TEXT,
  p_message     TEXT,
  p_error_name  TEXT DEFAULT NULL,
  p_code        TEXT DEFAULT NULL,
  p_stack       TEXT DEFAULT NULL,
  p_source      TEXT DEFAULT 'client',
  p_url         TEXT DEFAULT NULL,
  p_tenant_id   UUID DEFAULT NULL,
  p_release     TEXT DEFAULT NULL,
  p_user_agent  TEXT DEFAULT NULL,
  p_context     JSONB DEFAULT '{}'
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id   UUID := auth.uid();
  v_tenant_id UUID;
  v_group_id  UUID;
  v_source    TEXT := CASE WHEN p_source IN ('client', 'api', 'edge_function', 'database')
                           THEN p_source ELSE 'client' END;
  v_context   JSONB := COALESCE(p_context, '{}');
BEGIN
  IF p_fingerprint IS NULL OR btrim(p_fingerprint) = '' OR p_message IS NULL THEN
    RETURN;
  END IF;

  -- Anyone can call this, so never trust the size of what arrives.
  IF pg_column_size(v_context) > 16384 THEN
    v_context := jsonb_build_object('truncated', true);
  END IF;

  -- Signed-out callers may only open a limited number of NEW groups per hour
  -- (repeats of known errors always count), so the table cannot be flooded
  -- with invented fingerprints.
  IF v_user_id IS NULL
     AND NOT EXISTS (SELECT 1 FROM app_error_groups WHERE fingerprint = left(p_fingerprint, 128))
     AND (SELECT count(*) FROM app_error_groups
          WHERE first_seen_at > now() - interval '1 hour'
            AND cardinality(affected_users) = 0) >= 50
  THEN
    RETURN;
  END IF;

  -- Only record the tenant when the caller really belongs to it; never let a
  -- client attach errors to someone else's tenant.
  IF p_tenant_id IS NOT NULL AND v_user_id IS NOT NULL AND EXISTS (
    SELECT 1 FROM tenant_users
    WHERE user_id = v_user_id AND tenant_id = p_tenant_id AND status = 'active'
  ) THEN
    v_tenant_id := p_tenant_id;
  END IF;

  INSERT INTO app_error_groups AS g (
    fingerprint, source, error_name, message, code, stack,
    occurrence_count, affected_users, first_seen_at, last_seen_at,
    last_url, last_tenant_id, release
  )
  VALUES (
    left(p_fingerprint, 128), v_source, left(p_error_name, 200), left(p_message, 2000),
    left(p_code, 50), left(p_stack, 8000),
    1, CASE WHEN v_user_id IS NULL THEN '{}' ELSE ARRAY[v_user_id] END, now(), now(),
    left(p_url, 1000), v_tenant_id, left(p_release, 100)
  )
  ON CONFLICT (fingerprint) DO UPDATE SET
    occurrence_count = g.occurrence_count + 1,
    last_seen_at     = now(),
    last_url         = EXCLUDED.last_url,
    last_tenant_id   = COALESCE(EXCLUDED.last_tenant_id, g.last_tenant_id),
    release          = COALESCE(EXCLUDED.release, g.release),
    stack            = COALESCE(EXCLUDED.stack, g.stack),
    affected_users   = CASE
                         WHEN v_user_id IS NULL OR v_user_id = ANY (g.affected_users)
                              OR cardinality(g.affected_users) >= 500
                         THEN g.affected_users
                         ELSE array_append(g.affected_users, v_user_id)
                       END,
    -- A closed error that comes back is a regression: reopen it.
    status           = CASE WHEN g.status IN ('resolved', 'ignored') THEN 'new' ELSE g.status END,
    regressed_at     = CASE WHEN g.status IN ('resolved', 'ignored') THEN now() ELSE g.regressed_at END,
    updated_at       = now()
  RETURNING g.id INTO v_group_id;

  INSERT INTO app_error_occurrences (group_id, tenant_id, user_id, url, user_agent, release, context)
  VALUES (v_group_id, v_tenant_id, v_user_id, left(p_url, 1000), left(p_user_agent, 500),
          left(p_release, 100), v_context);

  -- Keep the latest 100 occurrences per group.
  DELETE FROM app_error_occurrences
  WHERE group_id = v_group_id
    AND id NOT IN (
      SELECT id FROM app_error_occurrences
      WHERE group_id = v_group_id
      ORDER BY occurred_at DESC
      LIMIT 100
    );
END;
$$;

REVOKE ALL ON FUNCTION public.log_app_error(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, UUID, TEXT, TEXT, JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.log_app_error(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, UUID, TEXT, TEXT, JSONB)
  TO anon, authenticated;

-- ============================================================================
-- 4. review_app_error(): SysAdmin changes the status
-- ============================================================================
CREATE OR REPLACE FUNCTION public.review_app_error(
  p_group_id UUID,
  p_status   TEXT,
  p_note     TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NOT public.is_sys_admin() THEN
    RAISE EXCEPTION 'Only a SysAdmin can review errors' USING ERRCODE = '42501';
  END IF;
  IF p_status NOT IN ('new', 'acknowledged', 'action_required', 'resolved', 'ignored') THEN
    RAISE EXCEPTION 'Unknown status %', p_status;
  END IF;

  UPDATE app_error_groups
  SET status          = p_status,
      resolution_note = COALESCE(NULLIF(btrim(p_note), ''), resolution_note),
      reviewed_by     = auth.uid(),
      reviewed_at     = now(),
      updated_at      = now()
  WHERE id = p_group_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Error group not found';
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.review_app_error(UUID, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.review_app_error(UUID, TEXT, TEXT) TO authenticated;
